import { mkdirSync, writeFileSync } from 'node:fs';

// This is our named extension library, not an upstream Substrait standard library.
const decimal = 'decimal<38,10>';
const numeric = ['i32', 'i64', 'fp64', decimal];
const impl = (args, result) => ({ args, result });
const arithmetic = numeric.flatMap(a => numeric.flatMap(b =>
  (a === decimal && b === 'fp64') || (a === 'fp64' && b === decimal) ? []
    : [impl([a,b], a === decimal || b === decimal ? decimal : 'fp64')]));
const scalar = [
  ['equal', [impl(['any1','any1'],'boolean')], 'SQL equality; string equality is accent-sensitive. Null propagates.'],
  ['lower', [impl(['string'],'string')], 'Lowercase using the backend Unicode implementation; no accent folding.'],
  ['is_null', [impl(['any1'],'boolean')], 'Required boolean: true exactly when the argument is null.'],
  ['is_not_null', [impl(['any1'],'boolean')], 'Required boolean: true exactly when the argument is non-null.'],
  ['and', [impl(['boolean','boolean'],'boolean')], 'SQL three-valued boolean conjunction.'],
  ['multiply', arithmetic, 'Multiply; integer/fp64 results are fp64. Decimal operations use precision 38 and scale 10. Null propagates.'],
  ['subtract', arithmetic, 'Subtract right from left; same numeric policy as multiply. Null propagates.'],
  ['divide', arithmetic, 'Divide left by right; zero denominator returns null. Same numeric policy as multiply.'],
  ['coalesce', [impl(['any1','any1'],'any1'),impl([decimal,'i32'],decimal)], 'First non-null argument; decimal accepts an integer fallback.'],
];
const aggregate = [
  ['sum', numeric.map(t => impl([t],t === decimal ? decimal : 'fp64')), 'Sum non-null values; empty input returns null.'],
  ['avg', numeric.map(t => impl([t],t === decimal ? decimal : 'fp64')), 'Mean of non-null values; empty input returns null.'],
  ['count', [impl(['any1'],'i64')], 'Required i64 count of non-null argument values.'],
  ['percentile_cont', numeric.map(t => impl([t,'fp64'],t === decimal ? decimal : 'fp64')), 'Continuous percentile of non-null values, position 1+p*(n-1). Fraction must be a literal in [0,1]. Decimal fractions have at most ten decimal places; decimal results round to scale 10. Empty input returns null.'],
];
const lines = ['%YAML 1.2', '---', '# Generated by scripts/generate-function-spec.mjs. Golden profile functions.'];
for (const [section, definitions] of [['scalar_functions',scalar],['aggregate_functions',aggregate]]) {
  lines.push(`${section}:`);
  for (const [name, implementations, description] of definitions) {
    lines.push(`  - name: ${name}`, `    description: ${JSON.stringify(description)}`, '    impls:');
    for (const { args, result } of implementations) {
      lines.push('      - args:');
      args.forEach((value,i) => lines.push(`          - name: arg${i}`, `            value: ${JSON.stringify(value)}`));
      lines.push('        nullability: DECLARED_OUTPUT', `        return: ${JSON.stringify(result)}`);
    }
  }
}
mkdirSync('spec', { recursive: true });
writeFileSync('spec/golden-functions.yaml', `${lines.join('\n')}\n`);
