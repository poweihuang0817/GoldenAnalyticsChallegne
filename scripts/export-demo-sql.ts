import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { format } from 'sql-formatter';
import { connect } from '../src/backend.js';
import { compilePlan, type LoweringDecision } from '../src/compiler.js';
import { challengeCatalog } from '../src/challenge.js';
import { queryExamples, recentOrdersPerCustomer } from '../src/queries.js';

// Fixed public samples only; values remain placeholders. Files are review copies,
// not standalone runnable SQL. Exact SQL/trace regression fixtures remain in test/.
const names = ['01-recent-orders', '02-london-count', '03-mexico-count', '04-average-units',
  '05-shipping-status', '06-freight-ratio', '07-percentile', '08-window-top-n'];
for (const backend of ['postgres', 'mysql', 'duckdb'] as const) {
  const db = connect(backend, { duckdbPath: ':memory:' });
  const expected = JSON.parse(readFileSync(`test/fixtures/sql-query-blocks/${backend}.json`, 'utf8'));
  const directory = `docs/sql-audit/${backend}`;
  mkdirSync(directory, { recursive: true });
  try {
    const examples = [...queryExamples, { name: 'Window top N', query: recentOrdersPerCustomer() }];
    for (const [i, {name, query}] of examples.entries()) {
      const trace: LoweringDecision[] = [];
      const compiled = compilePlan(db, query.toSubstrait(), challengeCatalog, { trace });
      assert.deepEqual({name, sql: compiled.sql, parameters: compiled.parameters, trace}, expected[i]);
      const header = [`-- ${name} | ${backend}`, '-- Generated by scripts/export-demo-sql.ts; display formatting only.',
        `-- Ordered sample parameters: ${JSON.stringify(compiled.parameters)}`,
        ...trace.map(e => `-- ${e.relationId} ${e.operation}: ${e.decision}; ${e.reason}`)].join('\n');
      writeFileSync(`${directory}/${names[i]}.sql`, header + '\n' + format(compiled.sql, {
        language: backend === 'postgres' ? 'postgresql' : backend, tabWidth: 2,
      }) + ';\n');
    }
  } finally { await db.destroy(); }
}
console.log('Exported 24 formatted SQL files, verified against compiler snapshots.');
